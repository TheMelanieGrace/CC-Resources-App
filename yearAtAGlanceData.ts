/**
 * Generate a descriptive Draft with AI topic from the Year at a Glance table for Cycles 1, 2, and 3.
 */
export function getYearAtAGlanceTopic(
  cycle: 1 | 2 | 3,
  week: number,
  checkedSubjects: Record<SubjectKey, boolean>
): string {
  const glanceTable =
    cycle === 1
      ? CYCLE_1_YEAR_AT_A_GLANCE
      : cycle === 2
      ? CYCLE_2_YEAR_AT_A_GLANCE
      : CYCLE_3_YEAR_AT_A_GLANCE;
  const weekData = glanceTable[week];

  if (!weekData) {
    return `CC Cycle ${cycle} Week ${week} memory work practice lines`;
  }

  const subjectOrder: { key: SubjectKey; label: string }[] = [
    { key: 'bible', label: 'Bible' },
    { key: 'history', label: 'History' },
    { key: 'science', label: 'Science' },
    { key: 'latin', label: 'Latin' },
    { key: 'english', label: 'English' },
    { key: 'geography', label: 'Geography' },
    { key: 'math', label: 'Math' },
    { key: 'timeline', label: 'Timeline' },
  ];

  const activeParts: string[] = [];

  for (const s of subjectOrder) {
    if (checkedSubjects[s.key] && weekData[s.key]) {
      activeParts.push(`${s.label}: ${weekData[s.key]}`);
    }
  }

  if (activeParts.length === 0) {
    return `CC Cycle ${cycle} Week ${week} memory work`;
  }

  return `CC Cycle ${cycle} Week ${week} memory work — ${activeParts.join('; ')}`;
}
