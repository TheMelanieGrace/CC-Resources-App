function isError503OrUnavailable(err: any): boolean {
  if (!err) return false;
  const status = err.status || err.statusCode || err.code;
  if (status === 503 || status === 429) return true;
  const msg = (err.message || String(err)).toLowerCase();
  return (
    msg.includes('503') ||
    msg.includes('unavailable') ||
    msg.includes('high demand') ||
    msg.includes('overloaded') ||
    msg.includes('resource exhausted') ||
    msg.includes('quota') ||
    msg.includes('rate limit')
  );
}

// Endpoint 1: Draft Sentences with AI for Tracing Tool
app.post('/api/gemini/draft', async (req, res) => {
  const { topic, fallbackModel } = req.body;

  if (!topic || typeof topic !== 'string' || !topic.trim()) {
    return res.status(400).json({
      error: 'Please provide a topic or prompt for handwriting sentences.',
    });
  }

  const cleanTopic = topic.trim();

  // Deterministic Bible check: answers directly from Carol Eichert memory work, never generated by LLM
  const bibleMatch = findBibleAnswerByQuery(cleanTopic);
  if (bibleMatch.found && bibleMatch.entry) {
    console.log(`[Draft] Deterministic Bible match: Cycle ${bibleMatch.cycle} Week ${bibleMatch.week}`);
    return res.json({
      sentences: bibleMatch.entry.lines,
      isBibleDirectMatch: true,
    });
  }

  if (!ai) {
    console.error('Gemini error: No API key found in process.env.API_KEY or process.env.GEMINI_API_KEY');
    return res.status(503).json({
      error: 'UNAVAILABLE: API key is not configured in environment.',
      code: 503,
    });
  }

  const prompt = `You are an educational assistant creating lines for a children's handwriting tracing worksheet.
Topic: "${cleanTopic}"

Provide 4 to 16 short traceable lines for this topic.
Strict requirements:
- Plain text ONLY.
- One traceable line per sentence, definition, or memory work fact.
- Between 4 and 16 short lines.
- Suitable for a children's handwriting practice worksheet.
- If the topic is phrased as a review or range (e.g., "Review packet for Latin in CC Cycle 3 weeks 1 to 5"), provide representative memory work lines covering that range.
- NO markdown formatting (no asterisks, no **bold**, no headers).
- NO bullets and NO numbering (no "1.", "-", "*").
- NO introductory or concluding commentary (do not say "Here are your sentences" or "I hope this helps").
- Just the clean lines of text, one per line.`;

  // Model selection: use supported Gemini models per @google/genai guidelines
  const models = fallbackModel
    ? [
        { name: 'gemini-3.6-flash', timeoutMs: 15000 },
        { name: 'gemini-3.1-flash-lite', timeoutMs: 15000 },
        { name: 'gemini-flash-latest', timeoutMs: 20000 },
        { name: 'gemini-3.8-flash', timeoutMs: 25000 },
      ]
    : [
        { name: 'gemini-3.1-flash-lite', timeoutMs: 15000 },
        { name: 'gemini-3.6-flash', timeoutMs: 15000 },
        { name: 'gemini-flash-latest', timeoutMs: 20000 },
        { name: 'gemini-3.8-flash', timeoutMs: 25000 },
      ];

  const errorLogs: string[] = [];
  let successfulText: string | null = null;
  let modelUsed: string | null = null;
  let has503Error = false;

  for (const modelItem of models) {
    try {
      console.log(`[Draft] Attempting generation with model "${modelItem.name}" for topic: "${cleanTopic}"`);
      const response = await ai.models.generateContent({
        model: modelItem.name,
        contents: prompt,
        config: {
          abortSignal: AbortSignal.timeout(modelItem.timeoutMs),
          thinkingConfig: {
            thinkingLevel: ThinkingLevel.MINIMAL,
          },
        },
      });

      const text = response.text || '';
      if (text.trim()) {
        successfulText = text;
        modelUsed = modelItem.name;
        console.log(`[Draft] Success with model "${modelItem.name}".`);
        break;
      }
    } catch (err: any) {
      if (isError503OrUnavailable(err)) {
        has503Error = true;
      }
      const errMsg = err?.message || (typeof err === 'object' ? JSON.stringify(err) : String(err));
      console.error(`[Draft] Model "${modelItem.name}" failed:`, errMsg);
      errorLogs.push(`${modelItem.name}: ${errMsg}`);
    }
  }

  if (!successfulText) {
    const combinedError = errorLogs.join('\n');
    console.error('[Draft] All models failed. Full details:\n', combinedError);
    if (has503Error) {
      return res.status(503).json({
        error: 'UNAVAILABLE: The model is experiencing high demand.',
        code: 503,
      });
    }
    return res.status(500).json({
      error: combinedError || 'All model attempts failed without an explicit error message.',
    });
  }

  // Parse plain text response into clean traceable lines
  const lines = successfulText
    .split('\n')
    .map((line) =>
      line
        .replace(/^[\s*\-•\d.)\]]+\s*/, '') // Remove bullets, numbers like 1., 1), etc.
        .replace(/\*\*/g, '') // Strip bold
        .replace(/^["]|["]$/g, '') // Strip wrapping quotes
        .trim()
    )
    .filter(
      (line) =>
        line.length > 0 &&
        !line.toLowerCase().startsWith('here are') &&
        !line.toLowerCase().startsWith('sure, here') &&
        !line.toLowerCase().startsWith('certainly')
    );

  const formattedTitle = cleanTopic.charAt(0).toUpperCase() + cleanTopic.slice(1);

  return res.json({
    title: formattedTitle,
    lines,
    modelUsed,
    reminder: 'Always verify every line against your Foundations Guide or curriculum guide.',
  });
});

// Helper to strictly sanitize expletive handling in sentence diagrams
function sanitizeDiagramAnalysis(data: any, originalSentence: string): any {
  if (!data || !Array.isArray(data.clauses)) return data;

  const isExpletiveSentence = (s: string) => {
    const clean = (s || '').trim();
    const startMatch = clean.match(/^(There|Here)\b/i);
    if (!startMatch) return false;
    const after = clean.slice(startMatch[0].length).trim();
    return /^(?:'s|is|are|was|were|will be|has been|have been|had been)\b/i.test(after);
  };

  data.clauses = data.clauses.map((clause: any) => {
    const textToCheck = originalSentence || clause.clause || '';
    if (isExpletiveSentence(textToCheck) || clause.expletive) {
      const match = textToCheck.trim().match(/^(There|Here)\b/i);
      const expWord = match ? match[0] : (clause.expletive || 'There');

      clause.expletive = expWord;

      // Remove from verb.modifiers so it never appears on a slanted modifier line under the verb
      if (Array.isArray(clause.verb?.modifiers)) {
        clause.verb.modifiers = clause.verb.modifiers.filter(
          (m: any) => (m.word || '').toLowerCase() !== expWord.toLowerCase()
        );
      }
      // Remove from subject.modifiers
      if (Array.isArray(clause.subject?.modifiers)) {
        clause.subject.modifiers = clause.subject.modifiers.filter(
          (m: any) => (m.word || '').toLowerCase() !== expWord.toLowerCase()
        );
      }

      // If subject was mistakenly set to the expletive word
      if ((clause.subject?.word || '').toLowerCase() === expWord.toLowerCase()) {
        if (Array.isArray(clause.complements) && clause.complements.length > 0) {
          const realComp = clause.complements.shift();
          clause.subject = {
            word: realComp.word,
            modifiers: realComp.modifiers || [],
          };
        }
      }

      if (clause.pattern !== 'S | Vi' && (!clause.complements || clause.complements.length === 0)) {
        clause.pattern = 'S | Vi';
      }

      const subjWord = clause.subject?.word || 'subject';
      const verbWord = clause.verb?.word || 'verb';

      // Table words: Word — expletive — placeholder, no job in the sentence pattern.
      if (!clause.kids) clause.kids = { pattern_why: '', words: [] };
      const words = Array.isArray(clause.kids.words) ? clause.kids.words : [];
      const filtered = words.filter(
        (w: any) => (w.word || '').toLowerCase() !== expWord.toLowerCase()
      );

      clause.kids.words = [
        {
          word: expWord,
          pos: 'expletive',
          job: 'placeholder, no job in the sentence pattern.',
        },
        ...filtered.map((w: any) => {
          if ((w.word || '').toLowerCase() === subjWord.toLowerCase()) {
            return { ...w, pos: w.pos === 'AV' ? 'N' : (w.pos || 'N'), job: 'S (Subject)' };
          }
          if ((w.word || '').toLowerCase() === verbWord.toLowerCase()) {
            return { ...w, pos: 'V', job: 'Vi (Intransitive Verb)' };
          }
          return w;
        }),
      ];

      // Synchronize note and pattern_why
      clause.note = `Pattern 1: Subject ("${subjWord}") with intransitive verb ("${verbWord}"). The opening "${expWord}" is an expletive (placeholder) diagrammed on its own short horizontal line floating above the subject, attached to nothing. The vertical divider between S and Vi crosses completely through the baseline.`;

      const curWhy = clause.kids.pattern_why || '';
      if (!curWhy.includes('expletive') || curWhy.toLowerCase().includes('adverb')) {
        clause.kids.pattern_why = `Pattern 1 (S | Vi): S stands for Subject ("${subjWord}") and Vi stands for Intransitive Verb ("${verbWord}"). The opening "${expWord}" is an expletive placeholder introducing the inverted sentence; it has no job in the sentence pattern and floats on its own short horizontal line above the subject. The vertical divider between subject and verb crosses completely through the baseline.`;
      }
    }
    return clause;
  });

  return data;
}

