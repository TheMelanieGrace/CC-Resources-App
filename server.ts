// Endpoint 3: Return Authentic Vulgate Latin Sentences (Static Bank)
app.post('/api/gemini/latin-sentences', (req, res) => {
  const { words } = req.body;
  if (!words || !Array.isArray(words) || words.length === 0) {
    return res.status(400).json({ error: 'Please provide an array of Latin words/phrases.' });
  }

  const sentences = words
    .map((w: { latin: string; meaning?: string }) => {
      const verse = getShortestVulgateVerseForWords([w.latin]);
      if (!verse) return null;
      return {
        latin_word: w.latin,
        sentence_latin: verse.latin,
        sentence_english: verse.english,
        reference: verse.reference,
      };
    })
    .filter(Boolean);

  return res.json({ sentences });
});

// Endpoint 3b: Return Authentic Vulgate "Use it in a sentence" for Review Packet Latin Weeks
app.post('/api/gemini/review-latin-sentences', (req, res) => {
  const { cycle, items } = req.body;
  if (!items || !Array.isArray(items) || items.length === 0) {
    return res.status(400).json({ error: 'Please provide items array for review Latin sentences.' });
  }

  const results = items
    .map((item: any) => {
      const weekNum = item.week;
      const targetCycle = (cycle || 3) as 1 | 2 | 3;
      const weekData = (LATIN_MEMORY_WORK[targetCycle] || []).find((w) => w.week === weekNum);
      const words = weekData ? extractWeekLatinWords(weekData.entries) : (item.weekWords || []);
      const verse = getShortestVulgateVerseForWords(words);
      if (!verse) return null;
      return {
        week: weekNum,
        latin: verse.latin,
        english: verse.english,
        reference: verse.reference,
        formatted: verse.latin,
      };
    })
    .filter(Boolean);

  return res.json({ sentences: results });
});

